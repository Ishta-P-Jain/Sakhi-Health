    """Return (category, fixed_message) if the text contains a red flag, else None."""
    norm = unicodedata.normalize("NFC", text)
    for cat in CATEGORIES:
        hit = any(p.search(norm) for p in _COMPILED[cat]) or any(
            w in norm for w in _NATIVE[cat]
        )
        if hit:
            msgs = MESSAGES[cat]
            return cat, msgs.get(language, msgs["en"])
    return None
